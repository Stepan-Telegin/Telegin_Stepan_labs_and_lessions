# Задача 19 (Вариант 10): x(t) = c * t^2 + t^3
eps = 1e-4
c_exact = 5 / 24  # Точное значение C (0.208333...)
k = 1 / 3  # Коэффициент сжатия lambda/3 при lambda = 1

c = 0.0  # Начальное приближение x_0(t) = 0 (c_0 = 0)
n_apr = 9  # Посчитано на бумаге: N_apr = 9

print(f"Точное решение: x*(t) = {c_exact:.6f} * t^2 + t^3\n")
print(f"{'Шаг n':<6} | {'Приближение c_n':<17} | {'Погрешность':<12}")
print("-" * 42)

# Метод простых итераций
for n in range(1, n_apr + 1):
    c_prev = c
    c = c_prev / 5 + 1 / 6  # Рекуррентная формула из интеграла

    # Погрешность в C[0; 1]: max|c - c*| * t^2 = |c - c*|
    error = abs(c - c_exact)
    print(f"{n:<6} | {c:<17.6f} | {error:<12.2e}")

print("-" * 42)
print(f"\nИтог: на шаге {n_apr} погрешность {error:.2e} < {eps}")
print(f"Приближенное решение: x(t) = {c:.6f} * t^2 + t^3")
